/** パッチノート一覧を公開日の新しい順で返す（データ配列の記述順に依存しない）。 */
export function listPatches(): PatchNote[] {
  return [...PATCHES].sort((a, b) => (a.releaseDate < b.releaseDate ? 1 : a.releaseDate > b.releaseDate ? -1 : 0));
}

/** バージョン文字列またはURLスラッグからパッチノートを引く。見つからない場合は undefined。 */
/**
 * slug（URLキー）でパッチを引く。version でも引けるようにすると `/patches/14-13` と `/patches/14.13`
 * が同一内容を返す重複URL（SEOの重複コンテンツ）になるため、正規URLである slug 単一キーで照合する。
 */
export function getPatchBySlug(slug: string): PatchNote | undefined {
  return PATCHES.find((p) => p.slug === slug);
}
